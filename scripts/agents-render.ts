// `make agents-render`: derive the generated agent definitions from the hand-written ones
// (BUILD.md §4.5). Deterministic: the same inputs give the same bytes, so a second run changes
// nothing and `git diff` stays quiet.
//
//   dual-review-cursor  the Cursor side of a dual review, as a separate agent. Always rendered: it
//                       is the fallback when the per-thread `harness`/`model` override cannot switch
//                       the credential (unverified, docs/KNOWN_LIMITATIONS.md).
//   ops-slack           the same agent plus a read-only agent-fleet MCP entry, only when
//                       EXOS_FLEET_MCP_URL is set (a loopback URL).
//   researcher-b        researcher in Mode B with a read-only GitHub MCP entry, only once Mode B is
//                       supported (it needs a sandbox for vault-backed MCP).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse, stringify } from "yaml";
import { hostOf } from "../doctor/src/agent-schema.ts";

type Front = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any -- parsed YAML

export interface RenderOptions {
  agentsDir: string;
  env: Record<string, string | undefined>;
  modeBSupported: boolean;
  githubMcpUrl?: string;
}

const FRONT = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/;

function readAgent(agentsDir: string, name: string): { front: Front; body: string } {
  const m = FRONT.exec(readFileSync(path.join(agentsDir, `${name}.md`), "utf8"));
  if (!m) throw new Error(`${name}.md has no front matter`);
  return { front: parse(m[1]!) as Front, body: m[2]! };
}

const isRelative = (p: unknown): p is string => typeof p === "string" && p.startsWith(".");
const deeper = (p: string): string => `../${p}`;

/** Paths in a definition are relative to its Markdown file; one folder deeper needs one more `../`. */
function reroot(front: Front): Front {
  const out: Front = { ...front };
  if (isRelative(out.harness)) out.harness = deeper(out.harness);
  if (Array.isArray(out.tools))
    out.tools = out.tools.map((t: unknown) => (isRelative(t) ? deeper(t) : t));
  if (Array.isArray(out.resources)) {
    out.resources = out.resources.map((r: Front) =>
      isRelative(r.path) ? { ...r, path: deeper(r.path) } : r,
    );
  }
  return out;
}

function compose(source: string, front: Front, body: string): string {
  return `---\n# Generated by scripts/agents-render.ts from agents/${source}.md. Do not edit.\n${stringify(front, { lineWidth: 0 })}---\n${body}`;
}

const LOOPBACK = new Set(["127.0.0.1", "localhost", "[::1]"]);

/** Returns the generated files keyed by their path relative to the repository root. */
export function renderAgents(opts: RenderOptions): Map<string, string> {
  const dir = path.join(path.basename(opts.agentsDir), "generated");
  const out = new Map<string, string>();

  // dual-review-cursor: the Cursor side as its own agent (the adapter cannot ask, so no always_ask).
  {
    const { front, body } = readAgent(opts.agentsDir, "dual-review");
    const derived: Front = reroot({
      ...front,
      name: "dual-review-cursor",
      description:
        "The Cursor side of a dual review, as a separate agent (fallback for the per-thread override).",
      harness: "cursor",
      model: { name: "auto", credential: "cursor" },
      permission_policy: { type: "always_allow" },
    });
    delete derived.tool_policies;
    out.set(path.join(dir, "dual-review-cursor.md"), compose("dual-review", derived, body));
  }

  const fleet = opts.env.EXOS_FLEET_MCP_URL;
  if (fleet) {
    const host = hostOf(fleet);
    if (host === null || !LOOPBACK.has(host)) {
      throw new Error(`EXOS_FLEET_MCP_URL must be a loopback URL, got ${JSON.stringify(fleet)}`);
    }
    const { front, body } = readAgent(opts.agentsDir, "ops-slack");
    const derived = reroot({
      ...front,
      mcp_servers: [
        { type: "url", name: "agent-fleet", url: fleet, permission_policy: { type: "always_ask" } },
      ],
    });
    out.set(path.join(dir, "ops-slack.md"), compose("ops-slack", derived, body));
  }

  if (opts.modeBSupported) {
    if (!opts.githubMcpUrl)
      throw new Error(
        "rendering researcher-b needs githubMcpUrl (the read-only GitHub MCP endpoint)",
      );
    const { front, body } = readAgent(opts.agentsDir, "researcher");
    const derived = reroot({
      ...front,
      name: "researcher-b",
      description:
        "The researcher agent in Mode B, with a read-only GitHub MCP server that needs the sandbox.",
      harness: "../harnesses/claude-sandboxed/claude-code-harness.ts",
      model: { name: front.model.name, credential: "claude-oauth" },
      mcp_servers: [
        ...front.mcp_servers,
        {
          type: "url",
          name: "github",
          url: opts.githubMcpUrl,
          permission_policy: { type: "always_ask" },
        },
      ],
    });
    out.set(path.join(dir, "researcher-b.md"), compose("researcher", derived, body));
  }
  return out;
}

export interface WriteReport {
  written: string[];
  unchanged: string[];
  removed: string[];
}

/** Writes the rendered files under `root` and removes generated `*.md` files that are no longer rendered. */
export function writeRendered(root: string, files: Map<string, string>): WriteReport {
  const report: WriteReport = { written: [], unchanged: [], removed: [] };
  const outDir = path.join(root, "agents", "generated");
  mkdirSync(outDir, { recursive: true });
  for (const [rel, content] of [...files.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const target = path.join(root, rel);
    if (existsSync(target) && readFileSync(target, "utf8") === content) {
      report.unchanged.push(rel);
    } else {
      writeFileSync(target, content);
      report.written.push(rel);
    }
  }
  for (const name of readdirSync(outDir)
    .filter((n) => n.endsWith(".md"))
    .sort()) {
    const rel = path.join("agents", "generated", name);
    if (!files.has(rel)) {
      rmSync(path.join(outDir, name));
      report.removed.push(rel);
    }
  }
  return report;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  const urlIndex = args.indexOf("--github-mcp-url");
  const root = process.cwd();
  const files = renderAgents({
    agentsDir: path.join(root, "agents"),
    env: process.env,
    modeBSupported: args.includes("--mode-b-supported"),
    githubMcpUrl: urlIndex >= 0 ? args[urlIndex + 1] : undefined,
  });
  const r = writeRendered(root, files);
  console.log(
    `agents rendered: ${r.written.length} written, ${r.unchanged.length} unchanged, ${r.removed.length} removed`,
  );
}
