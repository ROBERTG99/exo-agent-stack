import { describe, expect, it } from "vitest";
import { isProvablySafeBash } from "../../stackd/src/shell-safety.ts";

const safe = (c: string) => isProvablySafeBash(c);

describe("isProvablySafeBash: read-only inspection a person need not look at twice", () => {
  it.each([
    "ls -la",
    "ls src",
    "ls -R src | head -n 20",
    "pwd",
    "cat README.md",
    "cat -n src/a.ts",
    "head -n 5 src/a.ts",
    "head -5 src/a.ts",
    "tail -n 20 build.log",
    "wc -l src/a.ts",
    "git status",
    "git status --short",
    "git diff --stat",
    "git diff --cached -- src/a.ts",
    "git diff main..feature",
    "git log --oneline -n 5",
    "git --no-pager log --graph",
    "git show HEAD~2:src/a.ts",
    "git rev-parse HEAD",
    "git ls-files src",
    "git blame -L 1,5 src/a.ts",
    "grep -rn TODO src | sort -u | uniq -c",
    "grep -n -e foo -e bar src/a.ts",
    "grep -rin --include='*.ts' todo .",
    "rg -n 'git push' src",
    "rg -n -g '*.ts' todo",
    "sort -n -k 2 data.txt",
    "uniq -c data.txt",
    "diff -u a.txt b.txt",
    "find . -name '*.ts' -type f",
    "find src -maxdepth 2 -type d",
    "echo hello",
    "echo 'a && b | c; d'", // operators inside quotes are text
    "printf '%s\\n' hello",
    "ls *.ts",
    "cat src/*.ts",
    "ls src/*/",
    "ls '.*'", // quoted: a literal name, not a pattern
    "git show 'HEAD@{1}'",
    "grep -n 'a{2}' x.txt",
    "echo \\{a,b\\}", // escaped braces are literal text
    "ls 2>&1",
    "cat a.txt >/dev/null",
    "cd src && ls",
    "/usr/bin/git status",
    "basename src/a.ts",
    "date +%Y",
    "true && false || true",
  ])("%s", (c) => {
    expect(safe(c)).toBe(true);
  });
});

describe("isProvablySafeBash: everything else is for the dashboard", () => {
  it.each([
    // the commands the first blacklist named, and the ways around it
    "git push origin main",
    "git  push",
    "git -c core.sshCommand=x push",
    "git -C /tmp push",
    "git --git-dir=/x push",
    "GIT_SSH_COMMAND=x git status",
    "/usr/bin/git  push",
    "g\\it push",
    'g""it push',
    "'git' push",
    "npm publish",
    "pnpm publish",
    "yarn publish",
    "curl https://example.org",
    "wget -q x",
    "ssh host",
    "scp a b:c",
    "nc -l 1234",
    // anything that writes: a later command could run what was written
    "git add src/a.ts",
    "git commit -m x",
    "git checkout main",
    "git reset --hard",
    "git stash",
    "git restore .",
    "git tag v1",
    "git branch -D x",
    "echo hello > out.txt",
    "echo x >> notes.md",
    "echo x > Makefile",
    "echo x > .git/hooks/pre-commit",
    "mkdir -p build",
    "touch x",
    "cp a b",
    "mv a b",
    "rm -rf build",
    "ln -s /etc x",
    "tee out.txt",
    "sed -i s/a/b/ x",
    // anything that runs code written in the repository
    "make check-fast",
    "make up",
    "pnpm test",
    "pnpm run lint",
    "pnpm exec vitest run",
    "pnpm install",
    "npm run typecheck",
    "npm install",
    "python3 -c 'import urllib.request'",
    "python script.py",
    "node -e 'fetch(1)'",
    "bash -c 'ls'",
    "sh script.sh",
    "eval ls",
    "sudo ls",
    "env ls",
    "xargs ls",
    "./run.sh",
    "tsx scripts/x.ts",
    // shell features that hide the program
    "echo $(whoami)",
    "echo `whoami`",
    "echo $HOME",
    "${SHELL} -c x",
    "ls; (cd /; ls)",
    "ls &",
    "cat <(ls)",
    "cat <<EOF\nx\nEOF",
    "{ ls; }",
    // expansions that turn a local-looking word into another path
    "cat {/etc/passwd,x}",
    "cat {..,x}/secret",
    "cat src/{a,b}.ts",
    "echo {a,b}",
    "ls .*",
    "ls ..*",
    "ls .[a-z]*",
    "cat src/.*",
    "printf -v x y",
    "printf -vfoo '%s' a",
    "printf -- '%s' a",
    // reading what an agent must not see, or leaving the working directory
    "cat /etc/hosts",
    "cat ~/.exo-agent-stack/dashboard-token",
    "cat ../secrets",
    "cat ../../.ssh/id_rsa",
    "ls /",
    "ls ~",
    "head -n 5 /etc/passwd",
    "grep -r token /",
    "grep -f /etc/passwd x",
    "find / -name x",
    "diff /etc/passwd x",
    "cat < /etc/passwd",
    "echo x > /etc/passwd",
    "ls > $OUT",
    "cd /",
    "cd ..",
    "cd",
    // flags that write, execute or read elsewhere
    "sort -o out.txt a.txt",
    "sort -ofoo a.txt",
    "sort -nro out a.txt",
    "sort --output=out a.txt",
    "sort --compress-program=sh a.txt",
    "sort --files0-from=list a.txt",
    "sort -T /tmp a.txt",
    "uniq a.txt out.txt",
    "find . -exec rm {} +",
    "find . -delete",
    "find . -fprint out",
    "find . -newer /etc/passwd",
    "rg --pre sh x",
    "rg -z x",
    "rg --no-config x",
    "grep --exclude-from=/etc/passwd x",
    "git log --output=Makefile",
    "git diff --output=Makefile",
    "git diff --ext-diff",
    "git diff --textconv",
    "git diff --no-index /etc/passwd x",
    "git show --open-files-in-pager=sh",
    "git log -O/etc/passwd",
    "git remote add x y",
    "git fetch",
    "git pull",
    "git clone x",
    "git config user.name x",
    "git submodule update",
    "git rebase -i HEAD~2",
    "git ls-files /etc",
    "git log /etc/passwd",
    "head -n abc a.txt",
    "tail -f build.log",
    // unparseable or odd
    "",
    "   ",
    "ls 'unterminated",
    'ls "unterminated',
    "ls \\",
    "|| ls",
    "ls &&",
    "ls ||| cat",
    "ls\u0000; curl x",
    "ls $'\\x3b' curl",
  ])("%j", (c) => {
    expect(safe(c)).toBe(false);
  });

  it("is not fooled by letter case in the program or the sub-command", () => {
    expect(safe("GIT status")).toBe(false);
    expect(safe("git PUSH")).toBe(false);
    expect(safe("NPM publish")).toBe(false);
    expect(safe("LS")).toBe(false);
  });

  it("refuses a very long command rather than parse it", () => {
    expect(safe(`echo ${"a".repeat(20_000)}`)).toBe(false);
  });
});
